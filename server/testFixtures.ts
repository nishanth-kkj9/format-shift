// --- output probes -----------------------------------------------------------
// Probes read at most the first 256 bytes of an output. `minBytes` catches
// "empty file" successes; `magic` catches "right MIME, wrong bytes" (e.g. an
// mp3 label on WAV data), which is the failure mode that matters most here.

/** True when the head carries `marker` as ASCII at `offset`. */
const markerAt =
  (marker: string, offset = 0) =>
  (head: Buffer): boolean =>
    head.subarray(offset, offset + marker.length).toString("latin1") === marker;

/** True when the head starts with `sequence` at `offset`. */
const bytesAt =
  (sequence: number[], offset = 0) =>
  (head: Buffer): boolean =>
    sequence.every((byte, i) => head[offset + i] === byte);

const anyOf =
  (...predicates: Array<(head: Buffer) => boolean>) =>
  (head: Buffer): boolean =>
    predicates.some((predicate) => predicate(head));

/** True when the head's text starts with one of `prefixes`. */
const textStarts =
  (...prefixes: string[]) =>
  (head: Buffer): boolean => {
    const text = head
      .toString("utf8")
      .replace(/^\uFEFF/, "")
      .trimStart();
    return prefixes.some((prefix) => text.startsWith(prefix));
  };

const firstLine = (head: Buffer): string => head.toString("utf8").split("\n")[0] ?? "";
/** MPEG audio frame sync (0xFFE0 mask) — what a bare MP3 stream starts with. */
const mpegAudioSync = (head: Buffer): boolean => head[0] === 0xff && (head[1] & 0xe0) === 0xe0;
/** ADTS sync (0xFFF1 / 0xFFF9) — what raw AAC starts with. */
const adtsSync = (head: Buffer): boolean => head[0] === 0xff && (head[1] & 0xf6) === 0xf0;
/** ISO-BMFF/EBML container markers. */
const ebmlHeader = bytesAt([0x1a, 0x45, 0xdf, 0xa3]);
const ftyp =
  (brand?: (head: Buffer) => boolean) =>
  (head: Buffer): boolean =>
    markerAt("ftyp", 4)(head) && (brand ? brand(head) : true);
const riff =
  (form: string) =>
  (head: Buffer): boolean =>
    markerAt("RIFF")(head) && markerAt(form, 8)(head);

