// --- fixture generation ------------------------------------------------------

/** Recipe for one registry source format (throws when the format has no fixture). */
export function fixtureRecipe(category: FileCategory, source: string): FixtureRecipe {
  const recipe = RECIPES[category]?.[source];
  if (!recipe) throw new Error(`No test fixture defined for ${category}/${source}`);
  return recipe;
}

/**
 * Materialize one source fixture into `dir` and return it. Binary formats are
 * written by ffmpeg so the bytes are a real encode; text formats are written
 * verbatim. Synchronous on purpose — the matrix suite builds every fixture in
 * `beforeAll` and must not race its own requests.
 */
export function buildSourceFixture(category: FileCategory, source: string, dir: string): SourceFixture {
  const recipe = fixtureRecipe(category, source);
  const outPath = join(dir, recipe.filename);
  if (recipe.text !== undefined) {
    writeFileSync(outPath, recipe.text, "utf8");
  } else {
    if (!FFMPEG_BIN) throw new Error("ffmpeg binary not available; cannot generate binary fixtures");
    try {
      execFileSync(
        FFMPEG_BIN,
        [
          "-hide_banner",
          "-loglevel",
          "error",
          "-nostdin",
          "-y",
          ...CATEGORY_INPUT[category],
          ...(recipe.args ?? []),
          outPath,
        ],
        { stdio: ["ignore", "ignore", "pipe"] }
      );
    } catch (error) {
      const stderr = (error as { stderr?: Buffer }).stderr?.toString("utf8") ?? String(error);
      throw new Error(`fixture generation failed for ${category}/${source}: ${stderr.trim()}`);
    }
  }
  return { filename: recipe.filename, mimetype: recipe.mimetype, bytes: readFileSync(outPath) };
}

let fixtureDir: string | null = null;

/**
 * Build every registry source fixture once per run, keyed `category/source`.
 * Iterating the registry (not the recipe table) means a newly registered source
 * format without a fixture fails here instead of being silently skipped.
 */
export function generateAllFixtures(): FixtureSet {
  fixtureDir ??= mkdtempSync(join(tmpdir(), "fs-fixtures-"));
  const fixtures: FixtureSet = new Map();
  for (const category of Object.keys(RECIPES) as FileCategory[]) {
    for (const source of CONVERSION_REGISTRY[category].sourceFormats) {
      fixtures.set(`${category}/${source}`, buildSourceFixture(category, source, fixtureDir));
    }
  }
  return fixtures;
}

/** Delete the per-run fixture directory (safe to call twice). */
export function releaseFixtures(): void {
  if (!fixtureDir) return;
  rmSync(fixtureDir, { recursive: true, force: true });
  fixtureDir = null;
}

/**
 * Output validator for a registry target. Throws when a target has no probe: an
 * unpinned output format must fail the matrix suite rather than pass silently.
 */
export function outputProbe(category: FileCategory, target: string): OutputProbe {
  const probe = PROBES[category]?.[target];
  if (!probe) throw new Error(`No output probe defined for ${category}->${target}`);
  return probe;
}

/** First `size` bytes of an output body (the window every probe reads). */
export function headOf(body: Buffer, size = 256): Buffer {
  return body.subarray(0, Math.min(size, body.length));
}
